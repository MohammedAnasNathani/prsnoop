def _stats_from(prs: list[PRRecord], reviews: int = 0):
    act = build_activity("t", prs, [], [], window_days=30)
    return act.stats


def test_check_gates_pass_and_fail():
    s = _stats_from([_pr(1), _pr(2)])
    gates = check_gates(s, min_prs=1, min_merged=1, min_merge_rate=50)
    assert all(g.passed for g in gates)
    gates = check_gates(s, min_prs=5, min_reviews=3)
    failed = [g for g in gates if not g.passed]
    assert len(failed) == 2
    assert failed[0].target == ">= 5"


def test_check_gates_merge_rate_and_latency():
    s = _stats_from([_pr(1), _pr(2), _pr(3, merged=False)])
    gates = check_gates(s, min_merge_rate=99)
    assert not gates[0].passed
    assert gates[0].actual == "67%"
    gates = check_gates(s, max_merge_days=10)
    assert gates[0].passed
    assert gates[0].actual.endswith("d")
    # no merges at all fails the latency gate honestly
    empty = _stats_from([_pr(2, merged=False)])
    gates = check_gates(empty, max_merge_days=1)
    assert gates[0].passed is False
    assert gates[0].actual == "no merges"


def test_ci_summary_markdown():
    prs = [_pr(1), _pr(2), _pr(3, merged=False)]
    act = build_activity("t", prs, [], [], window_days=30)
