def test_replay_command_renders_offline(tmp_path, capsys):
    prs = [_pr(1), _pr(4, merged=False, adds=30)]
    act = build_activity("t", prs, [], [], window_days=30)
    snap = tmp_path / "snap.json"
    snap.write_text(json.dumps(act.to_dict()), encoding="utf-8")
    rc = cli.run(["replay", str(snap)])
    assert rc == 0
    out = capsys.readouterr().out
    assert "prsnoop | t" in out
    # json replay goes through the same snapshot
    rc = cli.run(["replay", str(snap), "-f", "json"])
    assert rc == 0
    payload = json.loads(capsys.readouterr().out)
    assert payload["stats"]["prs_authored"] == 2


