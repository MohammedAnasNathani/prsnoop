def test_activity_round_trip_preserves_everything():
    prs = [_pr(1), _pr(3, merged=False, adds=40)]
    act = build_activity("t", prs, [], [], window_days=30)
    restored = Activity.from_dict(act.to_dict())
    assert restored.user == "t"
    assert len(restored.prs) == 2
    assert restored.prs[0].state == "merged"
    assert restored.prs[0].merged_at is not None
    assert restored.stats.prs_authored == 2
    assert restored.stats.top_repos == act.stats.top_repos
    assert restored.stats.day_activity == act.stats.day_activity
    # second round trip is stable
    assert restored.to_dict() == act.to_dict()


def test_activity_round_trip_with_trend():
    from prsnoop.stats import TrendDelta, build_trend

    prs = [_pr(1), _pr(2)]
    act = build_activity("t", prs, [], [], window_days=30)
    prev = build_activity("t", [_pr(20)], [], [], window_days=30)
    act.trend = build_trend(act.stats, prev.stats)
    restored = Activity.from_dict(act.to_dict())
    assert len(restored.trend) == len(act.trend)
    first = restored.trend[0]
    assert isinstance(first, TrendDelta)
    assert first.key == act.trend[0].key
    assert first.current == act.trend[0].current


