def _open_item(number: int, age_days: int, author: str = "dev") -> dict:
    created = datetime.now(timezone.utc) - timedelta(days=age_days)
    return {
        "number": number,
        "title": f"pr {number}",
        "html_url": f"https://github.com/acme/app/pull/{number}",
        "state": "open",
        "created_at": created.isoformat().replace("+00:00", "Z"),
        "updated_at": created.isoformat().replace("+00:00", "Z"),
        "user": {"login": author},
        "draft": False,
        "labels": [],
        "comments": 0,
    }


def test_fetch_radar_ages_and_buckets():
    items = [
        _open_item(1, 1),
        _open_item(2, 20),
        _open_item(3, 45),
        _open_item(4, 8),
    ]
    report = fetch_radar(_RadarFake(items), "acme/app")
    assert report.total_open == 4
    buckets = report.buckets
    assert buckets["fresh"] == 1 and buckets["stale"] == 1
    assert buckets["ancient"] == 1 and buckets["aging"] == 1
    assert report.entries[0].age_days == 45  # oldest first
    assert report.median_age_days == 14.0
    assert report.entries[0].is_quiet


def test_radar_renders():
    items = [_open_item(7, 33, author="sam"), _open_item(2, 1)]
    report = fetch_radar(_RadarFake(items), "acme/app")
    table = render_radar_table(report)
    assert "prsnoop radar | acme/app" in table
    assert "ancient" in table and "sam" in table
    md = render_radar_markdown(report)
    assert "# Radar: acme/app" in md
    assert "[#7]" in md
    csv_out = render_radar_csv(report)
    lines = csv_out.strip().splitlines()
    assert lines[0].startswith("number,age_days")
    assert "7,33,ancient,sam" in lines[1]


