def test_pr_key_diffing():
    prs_a = [_pr(1, number=1), _pr(2, number=2, merged=False)]
    act_a = build_activity("t", prs_a, [], [], window_days=30)
    prs_b = prs_a + [_pr(3, number=3, merged=False)]
    act_b = build_activity("t", prs_b, [], [], window_days=30)
    assert pr_keys(act_a) == {"acme/app#1", "acme/app#2"}
    new, gone = diff_keys(pr_keys(act_a), pr_keys(act_b))
    assert new == {"acme/app#3"} and not gone
    # first tick reports nothing as new
    assert diff_keys(None, pr_keys(act_b)) == (set(), set())


