def test_wrapped_merge_and_discussion_records():
    fast = _pr(10, number=1, title="quick")  # merged 0.5d later
    slow = _pr(40, number=2, title="slow one")
    # make the slow one genuinely slow: merged 12 days after creation
    slow.merged_at = slow.created_at + timedelta(days=12)
    chatty = _pr(20, number=3, merged=False, title="debate", comments=42)
    act = build_activity("t", [fast, slow, chatty], [], [], window_days=90)
    w = build_wrapped(act)
    assert w.fastest_pr_title == "quick"
    assert w.slowest_pr_days == 12.0
    assert w.hottest_pr_title == "debate"
    assert w.hottest_pr_comments == 42
    table = render_wrapped_table(w)
    assert "Fastest merge" in table and "Slowest merge" in table
    assert "Most discussed" in table and "42 comments" in table
    payload = w.to_dict()
    assert payload["hottest_pr_url"].endswith("/pull/3")


def test_wrapped_records_absent_without_merges():
    act = build_activity("t", [_pr(5, merged=False, comments=0)], [], [], window_days=30)
    w = build_wrapped(act)
    assert w.fastest_pr_title is None and w.slowest_pr_title is None
    table = render_wrapped_table(w)
    assert "Fastest merge" not in table
