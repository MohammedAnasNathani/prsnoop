def _pr(
    days_ago: float,
    repo: str = "acme/app",
    merged: bool = True,
    adds: int = 150,
    comments: int = 0,
    number: int = 1,
    title: str = "add thing",
) -> PRRecord:
    created = datetime.now(timezone.utc) - timedelta(days=days_ago)
    merged_at = created + timedelta(days=0.5) if merged else None
    return PRRecord(
        repo=repo,
        number=number,
        title=title,
        url=f"https://github.com/{repo}/pull/{number}",
        state="merged" if merged else "open",
        created_at=created,
        merged_at=merged_at,
        additions=adds,
        deletions=adds // 3,
        changed_files=2,
        comments=comments,
    )


